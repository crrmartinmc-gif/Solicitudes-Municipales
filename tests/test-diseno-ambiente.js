const fs=require('fs'),assert=require('assert'),cp=require('child_process');
const css=fs.readFileSync('ambiente-lomas-theme.css','utf8');
const installer=fs.readFileSync('instalar-diseno-ambiente.ps1','utf8');
let n=0;const check=(c,m)=>{assert.ok(c,m);n++};
check(css.includes('#login'),'aplica estilo login');
check(css.includes('.agenda-item'),'aplica estilo agenda');
check(css.includes('.nav button.active'),'aplica estilo navegación');
check(css.includes('.card'),'aplica estilo tarjetas');
check(css.includes('background:#fff'),'usa fondo blanco');
check(css.includes('#13885f'),'usa verde institucional');
check(css.includes('@media(max-width:700px)'),'incluye versión móvil');
check(installer.includes('RESPALDO-SOLICITUDES-DISENO'),'respaldo automático');
check(installer.includes('clasp clone $scriptId'),'clona proyecto original antes de editar');
check(installer.includes('clasp push'),'sube cambios con clasp');
check(!installer.includes('clasp deploy'),'no altera publicación sin pruebas');
check(installer.includes('$oldScript.Value -cne $newScript.Value'),'protege JavaScript');
check(installer.includes('Compare-Object $oldIds $newIds'),'protege IDs');
check(installer.includes('if($ok -ne'), 'requiere confirmación');
check(installer.includes('ambiente-lomas.png'),'usa el logo existente del repositorio Choferes');
check(!css.includes('!important;background:#091322'),'no conserva tema oscuro');
const logoInstaller=fs.readFileSync('agrandar-logo.ps1','utf8');
check(css.includes('transform:scale(2)'), 'logo ampliado en escritorio');
check(css.includes('transform:scale(1.55)'), 'logo ampliado en celular');
check(logoInstaller.includes('AL_LOGO_BIG_V1'), 'parche visual idempotente');
check(logoInstaller.includes("if($oldNoCss -cne $newNoCss)"), 'nada cambia fuera del CSS');
check(logoInstaller.includes("clasp deploy -i $deployment"), 'publica sobre la misma URL');
check(!logoInstaller.includes('restablecerClavesVisiblesAPPSECRETARIA()'), 'no toca claves');
check(logoInstaller.includes("RESPALDO-SOLICITUDES-LOGO"), 'respaldo del proyecto antes de editar');
console.log('OK: '+n+' verificaciones del rediseño sin modificar el backend.');
