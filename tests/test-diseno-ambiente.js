const fs=require('fs'),assert=require('assert');
const css=fs.readFileSync('ambiente-lomas-theme.css','utf8');
const installer=fs.readFileSync('instalar-diseno-ambiente.ps1','utf8');
const official=fs.readFileSync('aplicar-logo-oficial.ps1','utf8');
const logo=fs.readFileSync('assets/logo-ambiente-lomas-horizontal.png');
let count=0;
function check(ok,msg){assert.ok(ok,msg);count++}
check(css.includes('#login'),'login mantiene sus estilos');
check(css.includes('.agenda-item'),'agenda mantiene sus estilos');
check(css.includes('.nav button.active'),'navegación mantiene sus estilos');
check(css.includes('background:#fff'),'tema blanco preservado');
check(css.includes('object-fit:contain;object-position:left center'),'logo horizontal sin recorte ni deformación');
check(css.includes('width:184px;height:63px'),'logo proporcionado en escritorio');
check(css.includes('width:132px;height:45px'),'logo proporcionado en celular');
check(css.includes('@media(max-width:700px)'),'adaptación móvil');
check(installer.includes('logo-ambiente-lomas-horizontal.png'),'las instalaciones futuras usan el logo aprobado');
check(logo.subarray(0,8).equals(Buffer.from([137,80,78,71,13,10,26,10])),'archivo logo PNG válido');
check(logo.readUInt32BE(16)===800&&logo.readUInt32BE(20)===267,'logo apaisado de 800 x 267');
check(logo.length>4000&&logo.length<60000,'logo optimizado para aplicación');
check(official.includes('RESPALDO-SOLICITUDES-LOGO-OFICIAL'),'respaldo de la versión vigente');
check(official.includes('clasp clone $scriptId'),'no usa versiones viejas del código');
check(official.includes('$original.Replace($oldTag, $newTag)'),'reemplaza imagen del encabezado');
check(official.includes('AL_LOGO_HORIZONTAL_V3'),'estilos nuevos y aislados');
check(official.includes('$beforeScripts[$i].Value -cne $afterScripts[$i].Value'),'JavaScript intacto');
check(official.includes('$beforeNoCss.Replace($oldTag, $newTag) -cne $afterNoCss'),'solo modifica imagen y CSS');
check(official.includes('clasp push'),'sube al proyecto original');
check(official.includes('clasp deploy -i $deploymentId'),'actualiza la MISMA implementación');
check(official.includes('AKfycbwyh-a1jGYe0ZpRu9IjImgMwVUoygIeZz0B-C5Cf3MWSS1vyiYCk3r9TgsEvQ_RlQ_y'),'usa URL confirmada por el usuario');
check(!official.includes('restablecerClavesVisiblesAPPSECRETARIA()'),'no modifica contraseñas');
console.log('OK: '+count+' comprobaciones del nuevo logo, interfaz y despliegue.');
